package main

import (
	"bufio"
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// routeAdapter writes a routing table for a harness whose plugin hands
// each tool call to one shared runner script. The runner reads a
// Claude-shaped payload, so the table is keyed by event and Claude tool
// name, and lists the guard scripts (base names) to run, in order:
//
//	# comment
//	PreToolUse<TAB>Bash<TAB>guard-a.sh guard-b.sh
//
// The whole file is generated, so the adapter creates it when missing.
type routeAdapter struct{ name string }

var routeTools = map[string][]string{
	"shell":       {"Bash"},
	"file_read":   {"Read", "Glob", "Grep", "LS"},
	"file_write":  {"Write"},
	"file_edit":   {"Edit", "MultiEdit", "NotebookEdit"},
	"web_fetch":   {"WebFetch"},
	"web_search":  {"WebSearch"},
	"agent_spawn": {"Agent", "Task"},
}

func (r routeAdapter) Name() string          { return r.name }
func (routeAdapter) DefaultConfig() string   { return "" }
func (routeAdapter) Create() bool            { return true }
func (routeAdapter) Events() map[string]bool { return setOf("PreToolUse", "PostToolUse") }
func (routeAdapter) ToolEvents() map[string]bool {
	return setOf("PreToolUse", "PostToolUse")
}
func (routeAdapter) Effects() map[string]bool { return setOf("", "none", "deny", "context") }
func (routeAdapter) Wires(kind string) bool   { return kind == "guard" }
func (routeAdapter) Unmapped(acts []string) []string {
	var out []string
	for _, a := range acts {
		base, _, _ := strings.Cut(a, ":")
		if base != "mcp_call" && routeTools[base] == nil {
			out = append(out, a)
		}
	}
	return out
}

func routeToolNames(acts []string) []string {
	plain, servers, all := splitActions(acts)
	var out []string
	seen := map[string]bool{}
	add := func(t string) {
		if !seen[t] {
			seen[t] = true
			out = append(out, t)
		}
	}
	for _, a := range plain {
		for _, t := range routeTools[a] {
			add(t)
		}
	}
	if all {
		add("mcp__*")
	}
	for _, s := range servers {
		add("mcp__" + s + "__*")
	}
	return out
}

func (a routeAdapter) Render(units []Resolved) (Wiring, error) {
	var w Wiring
	for _, u := range wiredUnits(a, units) {
		name := u.ScriptName()
		if name == "" {
			return w, fmt.Errorf("unit %q: a routed guard needs script", u.Unit)
		}
		for _, ev := range u.On {
			var tools []string
			if m, ok := u.MatchFor(ev); ok {
				tools = strings.Split(m, "|")
			} else {
				tools = routeToolNames(u.Actions)
			}
			for _, t := range tools {
				w.Entries = append(w.Entries, Entry{Event: ev, Matcher: t, Command: name, Unit: u.Unit})
			}
		}
	}
	return w, nil
}

func (routeAdapter) Load(b []byte) (Wiring, error) {
	var w Wiring
	sc := bufio.NewScanner(bytes.NewReader(b))
	n := 0
	for sc.Scan() {
		n++
		line := sc.Text()
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 3 {
			return w, fmt.Errorf("line %d: want event<TAB>tool<TAB>scripts", n)
		}
		for _, s := range strings.Fields(f[2]) {
			w.Entries = append(w.Entries, Entry{Event: f[0], Matcher: f[1], Command: s})
		}
	}
	return w, sc.Err()
}

func (a routeAdapter) Apply(_ []byte, w Wiring, _ Wiring) ([]byte, error) {
	var keys []string
	lists := map[string][]string{}
	for _, e := range w.Entries {
		if strings.ContainsAny(e.Event+e.Matcher+e.Command, "\t\n ") {
			return nil, fmt.Errorf("route %s %s %s: blank in a field", e.Event, e.Matcher, e.Command)
		}
		k := e.Event + "\t" + e.Matcher
		if _, ok := lists[k]; !ok {
			keys = append(keys, k)
		}
		lists[k] = append(lists[k], e.Command)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by yadm-agents for %s. Do not edit; change the units file.\n", a.name)
	b.WriteString("# event<TAB>tool<TAB>guard scripts, run in parallel; the first refusal in list order wins.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s\t%s\n", k, strings.Join(lists[k], " "))
	}
	return b.Bytes(), nil
}

func (routeAdapter) Rows(w Wiring) []string {
	pos := map[string]int{}
	var rows []string
	for _, e := range w.Entries {
		k := e.Event + "\t" + e.Matcher
		rows = append(rows, fmt.Sprintf("%s\t#%d\t%s", k, pos[k], e.Command))
		pos[k]++
	}
	sort.Strings(rows)
	return rows
}

func (routeAdapter) Unowned([]byte) (any, error) { return nil, nil }
